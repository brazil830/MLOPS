export const DEFAULT_PERSONA_IMAGE = '/personas/mother.jpg';

export function getPersonaImage(personaId, emotion = 'neutral') {
  if (!personaId) return DEFAULT_PERSONA_IMAGE;
  const persona = PERSONAS.find(p => p.id === personaId);
  if (persona) {
    if (emotion && persona.emotionImages && persona.emotionImages[emotion]) {
      return persona.emotionImages[emotion];
    }
    return persona.image || PERSONA_IMAGE_MAP[personaId] || DEFAULT_PERSONA_IMAGE;
  }
  return PERSONA_IMAGE_MAP[personaId] || DEFAULT_PERSONA_IMAGE;
}

